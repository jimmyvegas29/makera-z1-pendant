import org.jetbrains.kotlin.gradle.dsl.JvmTarget

/**
 * Everything except the Android shell: protocol, link, jog engine, hotkeys, view model and the
 * whole Compose UI (Compose Multiplatform). Android and iOS supply the few platform pieces
 * (preferences, files, haptics, clock, back button, hotkey file import/export) in androidMain /
 * iosMain. iOS framework: `Shared` (static), built on a Mac; the Xcode project isn't in the repo yet.
 */
plugins {
    id("org.jetbrains.kotlin.multiplatform")
    id("com.android.library")
    id("org.jetbrains.compose")
    id("org.jetbrains.kotlin.plugin.compose")
}

/** BuildInfo.VERSION = the app's version (gradle.properties), for the update check. */
val buildInfoDir = layout.buildDirectory.dir("generated/buildinfo/kotlin")
val generateBuildInfo by tasks.registering {
    val version = providers.gradleProperty("pendantVersionName")
    val out = buildInfoDir
    inputs.property("version", version)
    outputs.dir(out)
    doLast {
        val f = out.get().file("com/z1pendant/BuildInfo.kt").asFile
        f.parentFile.mkdirs()
        f.writeText("package com.z1pendant\n\n/** Generated by :shared:generateBuildInfo from gradle.properties. */\n" +
            "object BuildInfo {\n    const val VERSION = \"${version.get()}\"\n}\n")
    }
}

